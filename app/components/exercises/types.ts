// app/components/exercises/types.ts

/**
 * Данные упражнения пользователя.
 *
 * Содержит основную информацию об упражнении
 * и текущий персональный максимум повторений.
 */
export type Exercise = {
  /** Уникальный идентификатор упражнения. */
  id: string;

  /** Отображаемое название упражнения. */
  name: string;

  /** Уникальный slug упражнения. */
  slug: string;

  /** Текущий персональный максимум повторений. */
  maxReps: number | null;

  /** Дата последнего обновления максимума. */
  maxUpdatedAt: string | null;
};
